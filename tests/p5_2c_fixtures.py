"""Fixtures shared by P5.2c's tests (``BRIEF_45``): synthetic cells in memory, and a synthetic ``output/`` and repository
holding every input ``offline.tier_statements`` reads, each record written by the ORIGINAL route that wrote the real one.

Not a test module -- the name carries no ``test_`` prefix -- so pytest collects nothing here.

WHY THE RECORDS ARE GENERATED BY THE ORIGINAL ROUTES
-----------------------------------------------------
The module refuses unless P5.2b's committed statements, P8.4b's V4 and V5, P5.1's P1 and P3, P5.2's stop-rule record and
the README note's means are reproduced from the cells it reads.  A synthetic record built by this file's own arithmetic
would test the module against this file; built by ``iql_correction.random_tier_statements``, ``att_rederivation.
_paired_differences``, ``spatial_mixing.score_p1`` / ``collapse_criterion``, ``tier_sweep.score_stop_rule`` and
``statistics.mean`` -- the routes that wrote the real ones -- it tests the module against them.

Format versions are the real records' (``p5.1-spatial/1.0``, ``p5.2-tier-sweep/1.0``, ``p8.4b-rederivation/1.0``).
Alignment convention: every cell is a full grid of :data:`SEEDS` x :data:`DRAWS`, one episode per ``(seed, draw)``, rows
in ``(seed, draw)`` order.
"""

from __future__ import annotations

import hashlib
import json
import statistics
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

import offline.tier_statements as tst

#: Three training seeds and four held-out draws: per-seed blocks and intervals both exist, and a tree stays small.
SEEDS: tuple[int, ...] = (101, 202, 303)
DRAWS: tuple[int, ...] = (1000, 1001, 1002, 1003)

#: ``att_ours`` levels, shaped like the committed record: ``bc`` first at ``maxpressure``; at ``fixedtime`` ``dt_spatial``,
#: ``dt_nomix`` and ``behaviour`` identical and ``bc`` identical to ``bc_top10_perix``; ``iql`` first at ``random``.
LEVELS: dict[tuple[str, str], float] = {
    ("dt_spatial", "mappo1000"): 197.0, ("dt_nomix", "mappo1000"): 158.0, ("bc", "mappo1000"): 169.0,
    ("bc_top10", "mappo1000"): 750.0, ("bc_top10_perix", "mappo1000"): 166.5, ("iql", "mappo1000"): 276.0,
    ("behaviour", "mappo1000"): 160.25, ("random", "mappo1000"): 260.5,
    ("dt_spatial_h4", "mappo1000"): 185.25, ("dt_nomix_h4", "mappo1000"): 158.5,
    ("dt_spatial", "maxpressure"): 168.0, ("dt_nomix", "maxpressure"): 167.25, ("bc", "maxpressure"): 166.0,
    ("bc_top10", "maxpressure"): 680.0, ("bc_top10_perix", "maxpressure"): 210.25, ("iql", "maxpressure"): 199.0,
    ("behaviour", "maxpressure"): 168.0,
    ("dt_spatial", "fixedtime"): 207.0, ("dt_nomix", "fixedtime"): 207.0, ("behaviour", "fixedtime"): 207.0,
    ("bc", "fixedtime"): 207.25, ("bc_top10_perix", "fixedtime"): 207.25, ("bc_top10", "fixedtime"): 207.5,
    ("iql", "fixedtime"): 204.0,
    ("dt_spatial", "random"): 254.5, ("dt_nomix", "random"): 255.25, ("bc", "random"): 272.0,
    ("bc_top10", "random"): 350.25, ("bc_top10_perix", "random"): 284.0, ("iql", "random"): 191.0,
}
#: P5.2b's corrected IQL cell at ``random``.
CORRECTED_IQL_LEVEL = 198.5

#: Cells that are the SAME episodes (``fixedtime``'s identities, and the re-rolled anchor): one family, one value set.
FAMILIES: dict[tuple[str, str], str] = {
    ("dt_spatial", "fixedtime"): "fixedtime_dt", ("dt_nomix", "fixedtime"): "fixedtime_dt",
    ("behaviour", "fixedtime"): "fixedtime_dt",
    ("bc", "fixedtime"): "fixedtime_bc", ("bc_top10_perix", "fixedtime"): "fixedtime_bc",
}


def _family(method: str, tier: str) -> str:
    return FAMILIES.get((method, tier), f"{method}@{tier}")


def _term(key: str, seed: int, draw: int) -> float:
    """A per-episode term exact in binary (a multiple of 1/64), different per family, seed and draw; the draw's
    coefficient depends on the family, so two families' difference varies from draw to draw."""
    h = sum(map(ord, key))
    return ((h + 7 * seed + (13 + h % 7) * draw) % 29 - 14) / 64.0


def episode(method: str, tier: str, seed: int, draw: int, *, level: float | None = None,
            key: str | None = None) -> dict[str, Any]:
    """One synthetic episode's per-episode values (``att_ours``, ``att_engine``, the companions, A5's count)."""
    key = _family(method, tier) if key is None else key
    base = LEVELS[(method, tier)] if level is None else float(level)
    ours = base + _term(key, seed, draw)
    engine = ours - 7.0 + ((3 * sum(map(ord, key)) + 5 * seed + 7 * draw) % 11 - 5) / 32.0
    created = 1300 + draw % 7
    never = (sum(map(ord, key)) + seed + draw) % 3
    return {"att_ours": ours, "att_engine": engine, "created": created, "entered": created - never,
            "never_entered": never, "entered_fraction": (created - never) / created,
            "horizon_vehicle_count": float(seed % 7 + draw % 5 + len(key) % 3), "episode_reward": -float(draw)}


def row(arm: str, seed: int, draw: int, values: Mapping[str, Any]) -> dict[str, Any]:
    """A merged row in the module's format (:class:`offline.tier_statements.Cell`)."""
    return {"arm": arm, "seed": int(seed), "draw_id": int(draw), **{key: values[key] for key in (
        "att_ours", "att_engine", "entered", "created", "never_entered", "entered_fraction", "horizon_vehicle_count",
        "episode_reward")}}


def cell(spec: tst.CellSpec, values: Mapping[tuple[int, int], Mapping[str, Any]]) -> tst.Cell:
    """A cell from per-``(seed, draw)`` values, rows in ``(seed, draw)`` order."""
    return tst.Cell(spec=spec, rows=tuple(row(spec.arm, seed, draw, values[(seed, draw)])
                                          for seed, draw in sorted(values)))


def spec(method: str, tier: str, *, source: str = "p5_2", arm: str | None = None) -> tst.CellSpec:
    """A hand-made spec for a unit test (not one of ``CELL_SPECS`` unless it happens to coincide)."""
    arm = arm if arm is not None else f"{method}@{tier}"
    return tst.CellSpec(cell_id=f"{source}:{arm}", method=method, tier=tier, source=source, arm=arm,
                        eval_file=f"{source}/eval_{tier}_{method}.json", manifest="SHA256SUMS_test.txt")


def simple_cell(method: str, tier: str, ours: Mapping[tuple[int, int], float],
                engine: Mapping[tuple[int, int], float] | None = None, *, source: str = "p5_2",
                arm: str | None = None) -> tst.Cell:
    """A hand-made cell whose ``att_ours`` (and ``att_engine``, default ``ours - 7``) the test states per episode."""
    values = {}
    for key, value in ours.items():
        engine_value = engine[key] if engine is not None else float(value) - 7.0
        values[key] = {"att_ours": float(value), "att_engine": float(engine_value), "created": 1300, "entered": 1300,
                       "never_entered": 0, "entered_fraction": 1.0, "horizon_vehicle_count": 10.0,
                       "episode_reward": -1.0}
    return cell(spec(method, tier, source=source, arm=arm), values)


def _logical(spec_: tst.CellSpec) -> tuple[str, str]:
    if spec_.cell_id == tst.CORRECTED_IQL:
        return ("iql_corrected", "random")
    return (spec_.method, spec_.tier)


def values_for(spec_: tst.CellSpec, seeds: Sequence[int], draws: Sequence[int]) -> dict[tuple[int, int], dict[str, Any]]:
    """Every episode of one of ``CELL_SPECS``; the re-rolled anchor is P5.1's anchor's episodes."""
    method, tier = _logical(spec_)
    if method == "iql_corrected":
        return {(s, d): episode("iql", "random", s, d, level=CORRECTED_IQL_LEVEL, key="iql_corrected")
                for s in seeds for d in draws}
    return {(s, d): episode(method, tier, s, d) for s in seeds for d in draws}


def synthetic_cells(seeds: Sequence[int] = SEEDS, draws: Sequence[int] = DRAWS) -> dict[str, tst.Cell]:
    """All 32 of ``CELL_SPECS``, in memory."""
    return {spec_.cell_id: cell(spec_, values_for(spec_, seeds, draws)) for spec_ in tst.CELL_SPECS}


