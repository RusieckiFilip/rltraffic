@dataclass(frozen=True)
class SyntheticTree:
    roots: tst.Roots
    pins: tst.Pins
    cells: dict[str, tst.Cell]
    seeds: tuple[int, ...]
    draws: tuple[int, ...]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_sums(output: Path, name: str, directory: str) -> None:
    """``output/<name>`` over every file under ``output/<directory>``, in ``sha256sum``'s format."""
    lines = [f"{sha256_file(path)}  {path.relative_to(output).as_posix()}"
             for path in sorted((output / directory).rglob("*")) if path.is_file()]
    (output / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


def _eval_payload(spec_: tst.CellSpec, cell_: tst.Cell, *, extra: Mapping[str, Any] | None = None) -> dict[str, Any]:
    from offline.dt_gate import EpisodeResult, _cell

    produced = [EpisodeResult(arm=r["arm"], seed=r["seed"], draw_id=r["draw_id"], att_horizon=r["att_ours"],
                              horizon_vehicle_count=r["horizon_vehicle_count"], episode_reward=r["episode_reward"])
                for r in cell_.rows]
    payload: dict[str, Any] = {
        "arm": spec_.arm, "method": spec_.method, "declared_gradient_steps": 40000, "engine_seed": 1000,
        "cell": _cell(produced),
        "episodes": [{"arm": e.arm, "seed": e.seed, "draw_id": e.draw_id, "att_horizon": e.att_horizon,
                      "horizon_vehicle_count": e.horizon_vehicle_count, "episode_reward": e.episode_reward}
                     for e in produced],
    }
    if spec_.source == "p5_1":
        payload.update({"format_version": "p5.1-spatial/1.0", "tier": "grid4x4_mappo1000", "smoke": False})
    else:
        payload.update({"format_version": "p5.2-tier-sweep/1.0", "tier": spec_.tier, "deterministic": False})
    payload.update(dict(extra or {}))
    return payload


def _p8_row(spec_: tst.CellSpec, r: Mapping[str, Any], checkpoint: str | None) -> dict[str, Any]:
    source = ({"kind": "checkpoint", "detail": "synthetic", "checkpoint": checkpoint} if checkpoint is not None
              else {"kind": "algorithmic", "detail": "synthetic"})
    return {
        "format_version": "p8.4b-rederivation/1.0", "scenario": "grid4x4", "tier": spec_.tier, "method": spec_.method,
        "arm": spec_.arm, "seed": r["seed"], "draw_id": r["draw_id"], "created": r["created"], "entered": r["entered"],
        "never_entered": r["never_entered"], "entered_fraction": r["entered_fraction"],
        "completed_at_horizon": r["entered"] - 20, "running_at_horizon": 20, "waiting_at_horizon": 0,
        "att_ours": r["att_ours"], "att_engine": r["att_engine"], "att_difference": r["att_ours"] - r["att_engine"],
        "horizon_vehicle_count": r["horizon_vehicle_count"], "episode_reward": r["episode_reward"], "seconds": 1.5,
        "seconds_rollout": 1.25, "committed_att_ours": r["att_ours"], "reproduces_committed": True,
        "policy_source": source,
    }


def _write_campaign(work: Path, rows: Sequence[Mapping[str, Any]]) -> str:
    """P8.4b's layout: a file per cell by P8.4b's own name, the manifest by its own builder, the marker."""
    from offline.att_rederivation import CellKey, campaign_manifest, cell_file_name

    keys = []
    for r in rows:
        key = CellKey(scenario="grid4x4", arm=r["arm"], seed=r["seed"], draw_id=r["draw_id"])
        keys.append(key)
        write_json(work / cell_file_name(key), r)
    manifest = campaign_manifest(keys, engine_seed=1000)
    write_json(work / "campaign_manifest.json", manifest)
    (work / "CAMPAIGN_COMPLETE").write_text(
        json.dumps({"declared_cells_sha256": manifest["declared_cells_sha256"]}) + "\n", encoding="utf-8")
    return str(manifest["declared_cells_sha256"])


def _episodes(cell_: tst.Cell, definition: str) -> list[Any]:
    from offline.iql_correction import episodes_from_rows

    return episodes_from_rows(cell_.rows, value_key=definition)


def _p8_block(cells: Mapping[str, tst.Cell], left: str, right: str) -> dict[str, Any]:
    """P8.4b's ``{arm: {(seed, draw): {definition: value}}}`` for two cells (``att_rederivation.load_cells``' shape)."""
    out: dict[str, Any] = {}
    for cell_id in (left, right):
        c = cells[cell_id]
        out[c.spec.arm] = {(r["seed"], r["draw_id"]): {"att_ours": r["att_ours"], "att_engine": r["att_engine"]}
                           for r in c.rows}
    return out


def _v_block(cells: Mapping[str, tst.Cell], contrast_id: str, left: str, right: str, verdict: Any) -> dict[str, Any]:
    from offline.att_rederivation import _paired_differences
    from offline.dt_gate import mean_ci95

    block = _p8_block(cells, left, right)
    out: dict[str, Any] = {"contrast_id": contrast_id, "by_definition": {}}
    for definition in ("att_ours", "att_engine"):
        differences = _paired_differences(block, cells[left].spec.arm, cells[right].spec.arm, definition)
        stats = mean_ci95(differences)
        low, high = stats.mean - stats.ci95, stats.mean + stats.ci95
        out["by_definition"][definition] = {"n_paired": len(differences), "mean_difference": float(stats.mean),
                                            "ci95_low": float(low), "ci95_high": float(high),
                                            "outcome": verdict(low, high)}
    return out


def write_synthetic_tree(root: Path, *, seeds: Sequence[int] = SEEDS, draws: Sequence[int] = DRAWS) -> SyntheticTree:
    """Everything ``load_inputs`` reads, in miniature, under ``root / "output"`` and ``root / "repo"``."""
    import offline.iql_correction as ic
    import offline.tier_sweep as ts
    from offline.att_rederivation import CellKey, cell_file_name
    from offline.spatial_mixing import _outcome_from_interval, collapse_criterion, score_p1

    root = Path(root)
    output, repo = root / "output", root / "repo"
    output.mkdir(parents=True, exist_ok=True)
    repo.mkdir(parents=True, exist_ok=True)
    cells = synthetic_cells(seeds, draws)
    specs = {spec_.cell_id: spec_ for spec_ in tst.CELL_SPECS}

    # P5.1's and P5.2's evaluation records, and P5.2's stop-rule record by P5.2's own scorer.
    payloads: dict[str, dict[str, Any]] = {}
    for cell_id, spec_ in specs.items():
        if spec_.source == "p5_2b":
            continue
        payloads[cell_id] = _eval_payload(spec_, cells[cell_id])
        write_json(output / spec_.eval_file, payloads[cell_id])
    stop = ts.score_stop_rule(payloads["p5_2:dt_spatial_h4@mappo1000"], payloads["p5_2:dt_nomix_h4@mappo1000"],
                              list(seeds))
    write_json(output / tst.P5_2_STOP_RULE_RECORD, {"format_version": "p5.2-tier-sweep/1.0",
                                                    "measurement": "Q0 stop rule",
                                                    **{k: v for k, v in stop.items() if k != "per_seed"}})
    write_sums(output, tst.P5_1_SUMS_NAME, "p5_1")
    write_sums(output, tst.P5_2_SUMS_NAME, "p5_2")

    # P8.4b's campaign over the 31 cells it rolled.
    p8_rows = []
    for cell_id, spec_ in specs.items():
        if spec_.source == "p5_2b":
            continue
        checkpoint = (None if spec_.method in ("behaviour", "random")
                      else str(output / spec_.source / "checkpoints" / f"{spec_.method}.pt"))
        p8_rows.extend(_p8_row(spec_, r, checkpoint) for r in cells[cell_id].rows)
    declared = _write_campaign(output / tst.P8_4B_DIR, p8_rows)

    # P5.2b's run: the corrected evaluation, its training record and its re-derivation campaign.
    corrected = cells[tst.CORRECTED_IQL]
    out = output / tst.P5_2B_RUN_DIR
    checkpoints = {seed: str(out / "p5_2" / "checkpoints" / f"grid4x4_random_iql_seed{seed}.pt") for seed in seeds}
    runs = [{"seed": seed, "checkpoint_path": checkpoints[seed], "state_dict_sha256": f"{seed:064d}",
             "gradient_steps": 40000, "training_rows": 12} for seed in seeds]
    write_json(output / tst.P5_2B_TRAINING_RECORD, {"format_version": "p5.2b-training/1.0", "seeds": list(seeds),
                                                    "runs": runs})
    provenance = {str(run["seed"]): {"checkpoint_path": run["checkpoint_path"],
                                     "state_dict_sha256": run["state_dict_sha256"]} for run in runs}
    write_json(output / specs[tst.CORRECTED_IQL].eval_file,
               _eval_payload(specs[tst.CORRECTED_IQL], corrected,
                             extra={"replicate": False, "model_provenance": provenance}))
    rederivation_rows = [_p8_row(specs[tst.CORRECTED_IQL], r, checkpoints[r["seed"]]) for r in corrected.rows]
    rederivation = _write_campaign(output / tst.P5_2B_REDERIVATION_DIR, rederivation_rows)
    write_sums(output, tst.P5_2B_SUMS_NAME, tst.P5_2B_RUN_DIR)
    p5_2b_sums = sha256_file(output / tst.P5_2B_SUMS_NAME)

    # P5.2b's artifact, by P5.2b's own composer and summaries.
    oos = list(ts.OUT_OF_SAMPLE_CELLS)
    original = {d: {(m, t): _episodes(cells[f"p5_2:{m}@{t}"], d) for m, t in oos} for d in ("att_ours", "att_engine")}
    after = {d: {**original[d], ("iql", "random"): _episodes(corrected, d)} for d in original}

    def flagged(statements: dict[str, Any]) -> dict[str, Any]:
        statements["q1"]["predictions_registered_on"] = "synthetic flag, the one field P5.2b's report adds"
        return statements

    original_iql = cells[tst.ORIGINAL_IQL]
    p5_2b = {
        "format_version": "p5.2b-correction/1.0",
        "cells": {
            "original": {"att_ours": ic.cell_summary(_episodes(original_iql, "att_ours")),
                         "att_engine": ic.cell_summary(_episodes(original_iql, "att_engine")),
                         "admission": ic.admission_summary(original_iql.rows)},
            "corrected": {"att_ours": ic.cell_summary(_episodes(corrected, "att_ours")),
                          "att_engine": ic.cell_summary(_episodes(corrected, "att_engine")),
                          "admission": ic.admission_summary(corrected.rows)},
        },
        "statements": {
            "att_ours": {"before": flagged(ic.random_tier_statements(original["att_ours"], with_hard_subset=True)),
                         "after": flagged(ic.random_tier_statements(after["att_ours"], with_hard_subset=True))},
            "att_engine": {"before": flagged(ic.random_tier_statements(original["att_engine"], with_hard_subset=False)),
                           "after": flagged(ic.random_tier_statements(after["att_engine"], with_hard_subset=False))},
        },
        "inputs": {"run_manifest": {"file": f"output/{tst.P5_2B_SUMS_NAME}", "sha256": p5_2b_sums}},
    }
    write_json(repo / tst.P5_2B_ARTIFACT, p5_2b)

    # P8.4b's V4 and V5, by P8.4b's own route.
    from offline.tier_sweep import stop_rule_verdict

    p8 = {"format_version": "p8.4b-rederivation/1.0", "contrasts": [
        _v_block(cells, "V4", "p5_1:dt_spatial@grid4x4_mappo1000", "p5_1:dt_nomix@grid4x4_mappo1000",
                 _outcome_from_interval),
        _v_block(cells, "V5", "p5_2:dt_spatial_h4@mappo1000", "p5_2:dt_nomix_h4@mappo1000", stop_rule_verdict),
    ]}
    write_json(repo / tst.P8_4B_ARTIFACT, p8)

    # P5.1's P1 and P3, by P5.1's own scorers.
    spatial = _episodes(cells["p5_1:dt_spatial@grid4x4_mappo1000"], "att_ours")
    nomix = _episodes(cells["p5_1:dt_nomix@grid4x4_mappo1000"], "att_ours")
    anchor = _episodes(cells[tst.ANCHOR_CELL], "att_ours")
    grid = {"format_version": "p5.1-spatial/1.0", "predictions": {
        "P1": score_p1(spatial, nomix),
        "P3": {"dt_spatial": collapse_criterion(spatial, anchor), "dt_nomix": collapse_criterion(nomix, anchor)}}}
    write_json(repo / tst.P5_1_GRID, grid)

    # The README note's means, by its own route (statistics.mean over each arm's P8.4b rows).
    tiers: dict[str, Any] = {}
    for tier in tst.TIERS:
        block = {}
        for definition in ("att_engine", "att_ours"):
            means = {}
            for method in ts.METHODS:
                source = "p5_1" if tier == "mappo1000" and method != "bc_top10_perix" else "p5_2"
                arm = f"{method}@grid4x4_mappo1000" if source == "p5_1" else f"{method}@{tier}"
                values = []
                for r in cells[f"{source}:{arm}"].rows:
                    path = output / tst.P8_4B_DIR / cell_file_name(CellKey(scenario="grid4x4", arm=arm, seed=r["seed"],
                                                                          draw_id=r["draw_id"]))
                    values.append(float(json.loads(path.read_bytes())[definition]))
                means[method] = statistics.mean(values)
            block[definition] = {"means": means, "order": sorted(means, key=means.get)}
        tiers[f"grid4x4/{tier}"] = block
    write_json(repo / tst.C1_NOTE, {"cells_read": len(p8_rows), "not_reproducing": 0, "tiers": tiers})

    pins = tst.Pins(
        p5_1_sums_sha256=sha256_file(output / tst.P5_1_SUMS_NAME),
        p5_2_sums_sha256=sha256_file(output / tst.P5_2_SUMS_NAME),
        p5_2b_sums_sha256=p5_2b_sums,
        p8_4b_declared_cells_sha256=declared,
        p5_2b_rederivation_declared_cells_sha256=rederivation,
        p5_2b_artifact_sha256=sha256_file(repo / tst.P5_2B_ARTIFACT),
        p8_4b_artifact_sha256=sha256_file(repo / tst.P8_4B_ARTIFACT),
        p5_1_grid_sha256=sha256_file(repo / tst.P5_1_GRID),
        c1_note_sha256=sha256_file(repo / tst.C1_NOTE),
    )
    return SyntheticTree(roots=tst.Roots(repo_root=repo, output_root=output), pins=pins, cells=cells,
                         seeds=tuple(seeds), draws=tuple(draws))


def install_protocol(monkeypatch: Any, tree: SyntheticTree) -> None:
    """Point ``dt_gate``'s held-out pool and training seeds at the synthetic tree's, where every caller reads them."""
    import offline.dt_gate as dt_gate

    monkeypatch.setattr(dt_gate, "HELD_OUT_DRAWS", tuple(tree.draws))
    monkeypatch.setattr(dt_gate, "TRAINING_SEEDS", tuple(tree.seeds))


def snapshot(root: Path) -> dict[str, tuple[str, int]]:
    """Every file under *root*: its sha256 and ``st_mtime_ns`` (the barrier tests compare two snapshots)."""
    return {path.relative_to(root).as_posix(): (sha256_file(path), path.stat().st_mtime_ns)
            for path in sorted(Path(root).rglob("*")) if path.is_file()}


def directories(root: Path) -> list[str]:
    return sorted(path.relative_to(root).as_posix() for path in Path(root).rglob("*") if path.is_dir())
