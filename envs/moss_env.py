    # Abstract method implementations
    # ------------------------------------------------------------------

    def _init_simulator(self) -> None:
        moss = self._import_moss()

        if self._eng is None:
            verbosity = self._verbose_level(moss)
            self._eng = moss.Engine(
                name=self._name,
                map_file=self._effective_map_path,
                person_file=self._person_path,
                start_step=self._start_step,
                step_interval=self._step_interval,
                seed=self._seed,
                verbose_level=verbosity,
                speed_stat_interval=self._speed_stat_interval,
                junction_yellow_time=self._junction_yellow_time,
                output_dir=self._output_dir,
                device=self._device,
            )
            self._intersections = self._extract_intersections()
            self._num_intersections = len(self._intersections)
            if self._num_intersections == 0:
                raise ValueError(
                    "No controllable (TL-bearing) junctions found in MOSS map: "
                    f"{self._map_path}"
                )

            controlled = [
                self._junction_index_by_id[ix.id] for ix in self._intersections
            ]
            from moss import TlPolicy

            if self._manual_control:
                self._eng.set_tl_policy_batch(controlled, TlPolicy.MANUAL)
                self._set_tl_phases_batch(controlled, [0] * len(controlled))
            else:
                self._eng.set_tl_policy_batch(controlled, TlPolicy.FIXED_TIME)
            self._global_max_speed = self._compute_global_max_speed()
            # Snapshot the fresh state so reset() can rewind cheaply.
            self._initial_checkpoint = self._eng.make_checkpoint()
        else:
            assert self._initial_checkpoint is not None
            self._eng.restore_checkpoint(self._initial_checkpoint)
            controlled = [
                self._junction_index_by_id[ix.id] for ix in self._intersections
            ]
            from moss import TlPolicy

            if self._manual_control:
                # Defensively re-apply MANUAL policy in case the checkpoint
                # didn't carry it over.
                self._eng.set_tl_policy_batch(controlled, TlPolicy.MANUAL)
                self._set_tl_phases_batch(controlled, [0] * len(controlled))
            else:
                self._eng.set_tl_policy_batch(controlled, TlPolicy.FIXED_TIME)

        self._applied_phase_by_id = {}
        self._last_action_applied = np.zeros(
            self._num_intersections, dtype=np.bool_
        )

    def _set_tl_phases_batch(
        self, junction_indices: list[int], phase_indices: list[int]
    ) -> None:
        assert self._eng is not None
        if not junction_indices:
            return
        junction_indices = [int(j) for j in junction_indices]
        phase_indices = [int(p) for p in phase_indices]
        batch_setter = getattr(self._eng, "set_tl_phase_batch", None)
        if callable(batch_setter):
            batch_setter(junction_indices, phase_indices)
            return
        for j_index, phase in zip(junction_indices, phase_indices):
            self._eng.set_tl_phase(j_index, phase)

    def _simulate(self, num_steps: int) -> None:
        assert self._eng is not None
        if self._manual_control:
            # Re-assert the phase most recently pushed to the engine (not
            # the control's current phase, which is only updated at the
            # end of a step and would clobber mid-step transition
            # segments).  Falls back to the control right after reset.
            self._set_tl_phases_batch(
                [
                    self._junction_index_by_id[ix.id]
                    for ix in self._intersections
                ],
                [
                    self._applied_phase_by_id.get(
                        ix.id,
                        self._phase_controls[i].current_phase()
                        if i < len(self._phase_controls)
                        else 0,
                    )
                    for i, ix in enumerate(self._intersections)
                ],
            )
        # Convert agent ``delta_time`` (seconds) into engine sub-steps.
        n_engine_steps = max(
            1, int(round(float(num_steps) / self._step_interval))
        )
        self._eng.next_step(n_engine_steps)

    def _set_phase(
        self,
        ix_idx: int,
        phase: int,
        duration: int | None = None,
    ) -> None:
        _ = duration
        assert self._eng is not None
        if not self._manual_control:
            return
        ix_info = self._intersections[ix_idx]
        j_index = self._junction_index_by_id[ix_info.id]
        self._eng.set_tl_phase(int(j_index), int(phase))
        self._applied_phase_by_id[ix_info.id] = int(phase)

    def _apply_segment(self, ix_idx: int, segment: PhaseSegment) -> None:
        if segment.kind == "phase":
            self._set_phase(ix_idx, segment.phase, segment.duration)
            return
        if segment.kind == "all_red":
            assert self._eng is not None
            if not self._manual_control:
                return
            ix_info = self._intersections[ix_idx]
            all_red_index = self._all_red_phase_index.get(ix_info.id)
            if all_red_index is None:
                raise ValueError(
                    f"No all-red phase was injected for junction "
                    f"{ix_info.id}."
                )
            j_index = self._junction_index_by_id[ix_info.id]
            self._eng.set_tl_phase(int(j_index), int(all_red_index))
            self._applied_phase_by_id[ix_info.id] = int(all_red_index)
            return
        raise ValueError(
            f"Unsupported transition segment kind for MOSS: {segment.kind}"
        )

    def _create_metrics(self) -> BaseMetrics | None:
        if self._eng is None:
            return None
        return MossMetrics(
            engine=self._eng,
            intersections=self._intersections,
            metric_names=self._metric_names,
            delta_time=self.delta_time,
            global_max_speed=self._global_max_speed,
        )

    def _structured_features(self) -> dict[str, StructuredFeature]:
        return MossStateFeatures.structured_features()

    def _get_info(self) -> dict[str, Any]:
        assert self._eng is not None

        lane_vehicle_count = (
            self._metrics.lane_vehicle_count()
            if self._metrics is not None
            else {}
        )
        lane_waiting = (
            self._metrics.lane_waiting_vehicle_count()
            if self._metrics is not None
            else {}
        )

        intersections_info = self._build_intersections_info(
            lane_vehicle_count,
            lane_waiting,
        )

        try:
            vehicle_count = int(self._eng.get_running_person_count())
        except Exception:
            vehicle_count = 0
        try:
            sim_time = float(self._eng.get_current_time())
        except Exception:
            sim_time = float(self._step_count * self.delta_time)

        info: dict[str, Any] = {
            "sim_time": sim_time,
            "vehicle_count": vehicle_count,
            "average_travel_time": (
                self._metrics.get("average_travel_time")
                if self._metrics is not None
                else self._safe_average_travel_time()
            ),
            "lane_vehicle_count": lane_vehicle_count,
            "lane_waiting_vehicle_count": lane_waiting,
            "step": self._step_count,
            "intersections": intersections_info,
        }
        if self._metrics is not None:
            info["metrics"] = self._metrics.compute_all()
        return info

    def _safe_average_travel_time(self) -> float:
        if self._eng is None:
            return 0.0
        try:
            val = float(self._eng.get_finished_person_average_traveling_time())
        except Exception:
            return 0.0
        return 0.0 if val != val else val  # filter NaN

    # ------------------------------------------------------------------
    # Cleanup
    # ------------------------------------------------------------------

    def close(self) -> None:
        """Release the MOSS engine handle.

        MOSS owns GPU resources; dropping the Python reference is enough
        for them to be released by the C++ destructor.
        """
        self._eng = None
        self._initial_checkpoint = None

        if self._tmp_map_dir is not None and os.path.isdir(self._tmp_map_dir):
            import shutil

            shutil.rmtree(self._tmp_map_dir, ignore_errors=True)
            self._tmp_map_dir = None
